export function parseCSVToPrices(csvText: string): Array<{ date: string; close: number }> {
  const lines = csvText.trim().split(/\r?\n/);
  if (lines.length < 2) return [];

  // Identify column indices from header
  const header = lines[0].toLowerCase().split(",").map(c => c.trim().replace(/^["']|["']$/g, ""));
  let dateIdx = header.findIndex(h => h.includes("date") || h.includes("time"));
  let closeIdx = header.findIndex(h => h.includes("close") || h.includes("price") || h.includes("adj"));

  // Default fallback if headers are not standard
  if (dateIdx === -1) dateIdx = 0;
  if (closeIdx === -1) closeIdx = 1;

  const points: Array<{ date: string; close: number }> = [];

  for (let i = 1; i < lines.length; i++) {
    const row = lines[i].trim();
    if (!row) continue;
    const parts = row.split(",").map(p => p.trim().replace(/^["']|["']$/g, ""));
    const rawDate = parts[dateIdx];
    const rawClose = parseFloat(parts[closeIdx]);

    if (rawDate && !isNaN(rawClose) && rawClose > 0) {
      // Normalise date to YYYY-MM-DD
      const parsedDate = new Date(rawDate);
      const isoDate = !isNaN(parsedDate.getTime()) 
        ? parsedDate.toISOString().slice(0, 10) 
        : rawDate.slice(0, 10);
      points.push({ date: isoDate, close: rawClose });
    }
  }

  // Sort ascending
  return points.sort((a, b) => a.date.localeCompare(b.date));
}
